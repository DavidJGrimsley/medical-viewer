"""Generate centered volume proxy box OBJ mesh with baked metric dimensions from metadata.json."""
import argparse
import json
import math
from pathlib import Path

VOLUME_WIDTH_METRES = 0.55

def compute_extents(metadata):
    grid = metadata.get("grid", {})
    bounds = grid.get("boundsRasMm")
    if not bounds or len(bounds) != 6:
        raise ValueError("Invalid boundsRasMm in metadata")
    spans = [bounds[i + 1] - bounds[i] for i in (0, 2, 4)]
    max_span = max(spans)
    if max_span <= 0:
        raise ValueError("Non-positive span in boundsRasMm")
    # Volume extent: X=R (span 0), Y=A (span 1, Viro depth Z), Z=S (span 2, Viro height Y)
    extent = [(span * VOLUME_WIDTH_METRES) / max_span for span in spans]
    # Half-extents in Viro coordinates:
    # Viro X = extent[0]
    # Viro Y (height) = extent[2]
    # Viro Z (length) = extent[1]
    hx = extent[0] / 2.0
    hy = extent[2] / 2.0
    hz = extent[1] / 2.0
    return extent, hx, hy, hz

def generate_obj(hx, hy, hz):
    lines = [
        "# Generated by tools/medical/generate_volume_box.py; do not edit.",
        "# Centered volume proxy box mesh with baked metric dimensions from metadata.json",
        "o VolumeProxyBox",
        "",
        "# Vertices (x, y, z)",
        f"v {-hx:.8f} {-hy:.8f} {-hz:.8f}",
        f"v {hx:.8f} {-hy:.8f} {-hz:.8f}",
        f"v {hx:.8f} {hy:.8f} {-hz:.8f}",
        f"v {-hx:.8f} {hy:.8f} {-hz:.8f}",
        f"v {-hx:.8f} {-hy:.8f} {hz:.8f}",
        f"v {hx:.8f} {-hy:.8f} {hz:.8f}",
        f"v {hx:.8f} {hy:.8f} {hz:.8f}",
        f"v {-hx:.8f} {hy:.8f} {hz:.8f}",
        "",
        "# Texture Coordinates (u, v)",
        "vt 0.00000000 0.00000000",
        "vt 1.00000000 0.00000000",
        "vt 1.00000000 1.00000000",
        "vt 0.00000000 1.00000000",
        "",
        "# Normals (nx, ny, nz)",
        "vn 0.00000000 0.00000000 1.00000000",
        "vn 0.00000000 0.00000000 -1.00000000",
        "vn 1.00000000 0.00000000 0.00000000",
        "vn -1.00000000 0.00000000 0.00000000",
        "vn 0.00000000 1.00000000 0.00000000",
        "vn 0.00000000 -1.00000000 0.00000000",
        "",
        "# Faces (v/vt/vn) with outward winding (CCW viewed from outside)",
        "# +Z face (Normal: 0, 0, 1)",
        "f 5/1/1 6/2/1 7/3/1",
        "f 5/1/1 7/3/1 8/4/1",
        "# -Z face (Normal: 0, 0, -1)",
        "f 2/1/2 1/2/2 4/3/2",
        "f 2/1/2 4/3/2 3/4/2",
        "# +X face (Normal: 1, 0, 0)",
        "f 6/1/3 2/2/3 3/3/3",
        "f 6/1/3 3/3/3 7/4/3",
        "# -X face (Normal: -1, 0, 0)",
        "f 1/1/4 5/2/4 8/3/4",
        "f 1/1/4 8/3/4 4/4/4",
        "# +Y face (Normal: 0, 1, 0)",
        "f 8/1/5 7/2/5 3/3/5",
        "f 8/1/5 3/3/5 4/4/5",
        "# -Y face (Normal: 0, -1, 0)",
        "f 1/1/6 2/2/6 6/3/6",
        "f 1/1/6 6/3/6 5/4/6",
        "",
    ]
    return "\n".join(lines)

def generate_volume_box(volumes_dir):
    volumes_dir = Path(volumes_dir)
    metadata_path = volumes_dir / "metadata.json"
    if not metadata_path.exists():
        raise FileNotFoundError(f"Metadata not found: {metadata_path}")
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    extent, hx, hy, hz = compute_extents(metadata)
    obj_content = generate_obj(hx, hy, hz)
    out_path = volumes_dir / "volume-box.obj"
    out_path.write_text(obj_content, encoding="utf-8", newline="\n")
    return out_path, extent

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate volume-box.obj from metadata.json")
    parser.add_argument(
        "--volumes-dir",
        type=Path,
        default=Path(__file__).resolve().parent.parent.parent / "assets" / "medical" / "volumes",
        help="Path to assets/medical/volumes directory",
    )
    args = parser.parse_args()
    out, ext = generate_volume_box(args.volumes_dir)
    print(f"Generated {out.name} with extent [{ext[0]:.6f}, {ext[1]:.6f}, {ext[2]:.6f}]")
